//  - Quantities are in the item's base unit (g / ml / pc).
//  - `costPerUnit` values are INDICATIVE PLACEHOLDERS (₹ per base unit) so food cost
//    reports work on day one. They are flagged `costIsEstimate` and get replaced
//    automatically by actual prices when a purchase order is received.
//  - Anything the SOPs mark "to be confirmed" is flagged `tbc` / `openItems` and
//    surfaced in the UI until someone confirms it.
//  - Shelf-life hours come from the shelf-life guide (lower bound of each range).
